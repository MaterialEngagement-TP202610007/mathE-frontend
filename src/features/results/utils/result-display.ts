interface SecondaryStyleSource {
  predominantStyle: string
  secondaryStyle?: string | null
  visualProbability: number
  auditoryProbability: number
  kinestheticProbability: number
}

const ALL_STYLES: VakStyleApi[] = ["Visual", "Auditory", "Kinesthetic"]

function probabilityOf(source: SecondaryStyleSource, style: VakStyleApi): number {
  if (style === "Visual") return source.visualProbability
  if (style === "Auditory") return source.auditoryProbability
  return source.kinestheticProbability
}

/**
 * Secondary style of a result. Prefers the backend `secondaryStyle` field and
 * otherwise derives it from the probabilities: the strictly highest
 * non-predominant style. Returns null when it cannot be identified (unknown
 * predominant style, a tie, or no positive probability).
 */
export function resolveSecondaryStyle(source: SecondaryStyleSource): VakStyleApi | null {
  const { predominantStyle, secondaryStyle } = source
  if (isVakStyleApi(secondaryStyle) && secondaryStyle !== predominantStyle) {
    return secondaryStyle
  }
  if (!isVakStyleApi(predominantStyle)) return null

  const [first, second] = ALL_STYLES.filter((s) => s !== predominantStyle)
  const p1 = probabilityOf(source, first)
  const p2 = probabilityOf(source, second)
  if (!Number.isFinite(p1) || !Number.isFinite(p2) || p1 === p2) return null

  const [style, probability] = p1 > p2 ? [first, p1] : [second, p2]
  return probability > 0 ? style : null
}
