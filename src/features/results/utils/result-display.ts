const FEEDBACK_SOURCE_LABELS: Record<string, string> = {
  gemini: "Generado por IA (Gemini)",
  predefined: "Respuesta estándar",
}

/**
 * Badge label for the origin of the narrative feedback. Returns null when the
 * source is missing or unknown, so callers render no badge instead of guessing.
 */
export function feedbackSourceLabel(source: string | null | undefined): string | null {
  return source ? (FEEDBACK_SOURCE_LABELS[source] ?? null) : null
}

/** True when the feedback was generated by the AI provider (not the static fallback). */
export function isAiFeedback(source: string | null | undefined): boolean {
  return source === "gemini"
}

/** The backend falls back to `simple_score` when the full classifier is unavailable. */
export function isProvisionalResult(classifierType: string | null | undefined): boolean {
  return classifierType === "simple_score"
}

